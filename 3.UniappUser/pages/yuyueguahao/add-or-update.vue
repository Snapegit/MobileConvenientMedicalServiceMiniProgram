	import wPicker from "@/components/w-picker/w-picker.vue";
    import xiaEditor from '@/components/xia-editor/xia-editor';
    import multipleSelect from "@/components/momo-multipleSelect/momo-multipleSelect";
	export default {
		data() {
			return {
				cross:'',
				ruleForm: {
				yishengzhanghao: '',
				yishengxingming: '',
				keshi: '',
				tupian: '',
				jiuzhenshijian: '',
				guahaofei: '',
				shuliang: '',
				yuyuexuzhi: '',
				},
				keshiOptions: [],
				keshiIndex: 0,
				// 登录用户信息
				user: {},
                ro:{
                   yishengzhanghao : false,
                   yishengxingming : false,
                   keshi : false,
                   tupian : false,
                   jiuzhenshijian : false,
                   guahaofei : false,
                   shuliang : false,
                   yuyuexuzhi : false,
                },
			}
		},
		components: {
			wPicker,
            xiaEditor,
            multipleSelect
		},
		watch:{
		},
		async onLoad(options) {
			let table = uni.getStorageSync("nowTable");
			// 获取用户信息
			let res = await this.$api.session(table);
			this.user = res.data;
			
			// ss读取
			this.ruleForm.yishengzhanghao = this.user.yishengzhanghao
			this.ro.yishengzhanghao = true;
			this.ruleForm.yishengxingming = this.user.yishengxingming
			this.ro.yishengxingming = true;
			this.ruleForm.keshi = this.user.keshi
			this.ro.keshi = true;


			// 下拉框
			res = await this.$api.option(`keshi`,`keshi`,{});
			this.keshiOptions = res.data;
            this.keshiOptions.unshift("请选择科室");

			// 如果有登录，获取登录后保存的userid
			this.ruleForm.userid = uni.getStorageSync("userid")
			if (options.refid) {
				// 如果上一级页面传递了refid，获取改refid数据信息
				this.ruleForm.refid = options.refid;
				this.ruleForm.nickname = uni.getStorageSync("nickname");
			}
			// 如果是更新操作
			if (options.id) {
				this.ruleForm.id = options.id;
				// 获取信息
				res = await this.$api.info(`yuyueguahao`, this.ruleForm.id);
				this.ruleForm = res.data;
			}
			// 跨表
			this.cross = options.cross;
			if(options.cross){
				var obj = uni.getStorageSync('crossObj');
				for (var o in obj){
					if(o=='yishengzhanghao'){
					this.ruleForm.yishengzhanghao = obj[o];
					this.ro.yishengzhanghao = true;
					continue;
					}
					if(o=='yishengxingming'){
					this.ruleForm.yishengxingming = obj[o];
					this.ro.yishengxingming = true;
					continue;
					}
					if(o=='keshi'){
					this.ruleForm.keshi = obj[o];
					this.ro.keshi = true;
					continue;
					}
					if(o=='tupian'){
					this.ruleForm.tupian = obj[o].split(",")[0];
					this.ro.tupian = true;
					continue;
					}
					if(o=='jiuzhenshijian'){
					this.ruleForm.jiuzhenshijian = obj[o];
					this.ro.jiuzhenshijian = true;
					continue;
					}
					if(o=='guahaofei'){
					this.ruleForm.guahaofei = obj[o];
					this.ro.guahaofei = true;
					continue;
					}
					if(o=='shuliang'){
					this.ruleForm.shuliang = obj[o];
					this.ro.shuliang = true;
					continue;
					}
					if(o=='yuyuexuzhi'){
					this.ruleForm.yuyuexuzhi = obj[o];
					this.ro.yuyuexuzhi = true;
					continue;
					}
				}
			}
			this.styleChange()
            this.$forceUpdate()
		},
		methods: {
			styleChange() {
				this.$nextTick(()=>{
					document.querySelectorAll('.radioText').forEach(el => {
					  el.removeAttribute('style')
					  const icon = {"color":"#666666"}
					  Object.keys(icon).forEach((key) => {
						el.style[key] = icon[key]
					  })
					})
					document.querySelectorAll('.radioTextActive').forEach(el => {
					  el.removeAttribute('style')
					  const icon = {"color":"#00babd"}
					  Object.keys(icon).forEach((key) => {
						el.style[key] = icon[key]
					  })
					})
					document.querySelectorAll('.checkText').forEach(el => {
					  el.removeAttribute('style')
					  const icon = {"color":"#666666"}
					  Object.keys(icon).forEach((key) => {
						el.style[key] = icon[key]
					  })
					})
					document.querySelectorAll('.checkTextActive').forEach(el => {
					  el.removeAttribute('style')
					  const icon = {"color":"#00babd"}
					  Object.keys(icon).forEach((key) => {
						el.style[key] = icon[key]
					  })
					})
					document.querySelectorAll('.uni-radio-input').forEach(el => {
					  el.removeAttribute('style')
					  const icon = {"border":"2rpx solid #999999","borderRadius":"100%","background":"#ffffff"}
					  Object.keys(icon).forEach((key) => {
						el.style[key] = icon[key]
