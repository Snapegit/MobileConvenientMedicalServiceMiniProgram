			// 下拉变化
			keshiChange(e) {
				this.keshiIndex = e.target.value
				this.ruleForm.keshi = this.keshiOptions[this.keshiIndex]
			},

			tupianTap() {
				let _this = this;
				this.$api.upload(function(res) {
					_this.ruleForm.tupian = 'file/' + res.file;
					_this.$forceUpdate();
